package org.example;

public class Relacionais {
    public static void main(String[] args){
        // Declarações de variaveis
        int a = 10;
        int b = 2;
        int maior;

        // Operadores aritméticos
        if ( a > b) {
            maior = a;
        } else {
            maior = b;
        }

        // exibindo resultados
        System.out.println("O maior número é : " + maior);
    }
}
